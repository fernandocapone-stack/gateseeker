/**
 * Domain model shared by every Gateseeker module.
 *
 * Three layers are kept apart on purpose and must never be merged:
 *   1. data reported by an intelligence source (evidence, severity, references);
 *   2. conclusions produced by deterministic rules (priority, rationale, verdict);
 *   3. explanations produced by AI (reserved field, not implemented, never decisive).
 */

export type Ecosystem = "npm" | "Packagist";

/** How trustworthy the version string of a lockfile entry is. */
export type VersionStatus =
  | "ok" // strict semver, resolvable in the registry
  | "missing" // no version field
  | "non-semver" // version present but not strict semver
  | "non-registry"; // git, file, link or tarball source; registry lookups do not apply

export interface Exposure {
  /** Declared in the root package's dependency maps and installed at top level. */
  direct: boolean;
  /** Reachable from a non-dev dependency path (not dev-only). */
  production: boolean;
}

/** One unique name@version across the whole lockfile. */
export interface Dependency {
  name: string;
  version: string | null;
  ecosystem: Ecosystem;
  versionStatus: VersionStatus;
  exposure: Exposure;
  /** Lockfile paths where this name@version appears. */
  paths: string[];
  /** Composer only: commit fixed in the lock, its VCS url and release time, used by supply-chain rules. */
  sourceReference?: string | null;
  sourceUrl?: string | null;
  releasedAt?: string | null;
}

export type QueryState =
  | "vulnerable"
  | "no-known-vulnerabilities"
  | "query-failed"
  | "not-queried";

export interface QueryRecord {
  dependency: string; // name@version
  state: QueryState;
  source: string; // e.g. "osv.dev"
  queriedAt: string | null; // ISO timestamp, null when not queried
  error: string | null; // present when state is "query-failed" or "not-queried"
}

export type SeverityTier = "CRITICAL" | "HIGH" | "MODERATE" | "LOW" | "UNKNOWN";

export interface CvssEntry {
  type: string; // "CVSS_V3", "CVSS_V4", ... preserved as given by the source
  vector: string;
  /** Base score computed locally. Only CVSS 3.x is scored in this version. */
  score: number | null;
}

export interface Severity {
  /** Tier derived by Gateseeker from the data below. */
  tier: SeverityTier;
  /** Qualitative severity declared by the source (e.g. GitHub Advisory "HIGH"). */
  declared: string | null;
  cvss: CvssEntry[];
}

export type FindingKind =
  | "dependency-vulnerability"
  | "insecure-pattern"
  | "supply-chain-anomaly"
  | "secret-exposure";

export type Priority = "P1" | "P2" | "P3" | "P4";

export interface Reference {
  type: string;
  url: string;
}

/** Raw facts from an intelligence source about a dependency, untouched. */
export interface DependencyEvidence {
  kind: "dependency-vulnerability";
  vulnerabilityId: string;
  aliases: string[];
  summary: string | null;
  details: string | null;
  published: string | null;
  modified: string | null;
  affectedRanges: unknown; // preserved verbatim for auditing
}

/** Facts about a code pattern match. `snippet` is sanitized and redacted. */
export interface PatternEvidence {
  kind: "insecure-pattern";
  ruleId: string;
  title: string;
  file: string;
  line: number;
  fileClass: string;
  snippet: string;
  message: string;
  details: Record<string, string | number | boolean | null> | null;
}

/** Facts behind a supply-chain finding: a curated advisory (advisories/) or a structural rule on the lockfile. */
export interface SupplyChainEvidence {
  kind: "supply-chain-anomaly";
  origin: "advisory" | "structural";
  advisoryId: string | null;
  ruleId: string | null;
  type: string;
  summary: string;
  indicators: string[];
  window: { start: string | null; end: string | null } | null;
  reviewedBy: string | null;
  reviewedAt: string | null;
  /** "verified": checked against the registry/baseline; "unverified": the check could not run; "not-applicable": no external check involved. */
  verification: "verified" | "unverified" | "not-applicable";
  details: Record<string, string | number | boolean | null> | null;
}

/** @deprecated name kept for readers of older code; use SupplyChainEvidence. */
export type AdvisoryEvidence = SupplyChainEvidence;

export type Evidence = DependencyEvidence | PatternEvidence | SupplyChainEvidence;

export interface Finding {
  id: string;
  kind: FindingKind;
  subject: string;
  evidence: Evidence;
  source: { name: string; queriedAt: string };
  severity: Severity;
  priority: Priority;
  /** Identifiers of the rules that produced `priority`, in application order. */
  rationale: string[];
  remediation: {
    fixedVersions: string[];
    action: string;
    /**
     * Rule conclusions in plain language (src/rules/remediation), written by
     * us and deterministic; never generated by a model. Optional so reports
     * from older versions stay valid.
     */
    /** What could happen, one sentence. */
    impact?: string;
    /** One to four short manual steps. */
    manualSteps?: string[];
    /** Text to paste into an AI coding tool. Built only from finding facts (paths, names, versions), never from file contents. */
    aiPrompt?: string;
  };
  references: Reference[];
  /** Reserved for a future, optional AI explanation. Always null in this version. */
  aiExplanation: null;
}

export type Verdict = "pass" | "fail" | "incomplete";

export type PatternsMode = "warn" | "gate";

export interface PatternsReport {
  filesScanned: number;
  filesSkippedIgnored: number;
  filesSkippedBinary: number;
  /** Files above the size limit that were not read, and the first 10 paths. Absent in reports from before 2026-10-30. */
  filesSkippedLarge?: number;
  largeFiles?: string[];
  bytesScanned: number;
  rulesRun: string[];
  suppressions: { file: string; line: number; ruleId: string; reason: string }[];
  invalidSuppressions: { file: string; line: number; text: string }[];
}

export interface Report {
  gateseekerVersion: string;
  runId: string;
  startedAt: string;
  finishedAt: string;
  project: {
    /** Lockfiles at the root that Gateseeker does not read (e.g. pnpm-lock.yaml). Absent in older reports. */
    unsupportedLockfiles?: string[];
    /** Directory scanned, or the lockfile's directory when only a lockfile was given. */
    rootPath: string;
    /** null when no package-lock.json was analyzed. */
    lockfilePath: string | null;
    lockfileSha256: string | null;
    lockfileVersion: number | null;
    name: string | null;
    /** Every lockfile analyzed (npm and/or Composer). */
    lockfiles: { path: string; kind: string; sha256: string; lockfileVersion: number | null }[];
  };
  /** Comparison with a previous lockfile, when --baseline was given. */
  baseline: {
    path: string;
    sha256: string;
    ecosystem: Ecosystem;
    packagesCompared: number;
    added: string[];
    removed: string[];
    changed: string[];
  } | null;
  /** Which analyses ran. Absent analyses are declared, not silently skipped. */
  analyses: {
    /** "not-supported": the project has only lockfiles Gateseeker cannot read yet (see project.unsupportedLockfiles). */
    dependencies: "analyzed" | "not-analyzed" | "not-supported";
    patterns: "analyzed" | "not-analyzed";
  };
  /** null when the pattern analysis did not run. */
  patterns: PatternsReport | null;
  dependencies: Dependency[];
  queries: QueryRecord[];
  findings: Finding[];
  summary: {
    dependencies: number;
    queried: number;
    byQueryState: Record<QueryState, number>;
    byPriority: Record<Priority, number>;
    byKind: Record<FindingKind, number>;
  };
  sources: { name: string; endpoint: string }[];
  gate: {
    failOn: Priority;
    /** "warn": pattern findings are reported but do not affect the verdict. */
    patternsMode: PatternsMode;
    /** Same switch for the structural supply-chain rules (GSK-SC-*). Curated advisory matches are always gated. */
    supplyChainMode: PatternsMode;
    verdict: Verdict;
    reason: string;
  };
  errors: string[];
  limitations: string[];
}
